# --- Latest resume helpers ---------------------------------------------------
async def _get_latest_resume(db: AsyncSession, user_id) -> Resume | None:
    result = await db.execute(
        select(Resume).where(Resume.user_id == user_id).order_by(Resume.created_at.desc()).limit(1)
    )
    return result.scalar_one_or_none()

async def _get_latest_resume_analysis(db: AsyncSession, user_id) -> dict | None:
    result = await db.execute(
        select(ResumeAnalysis)
        .where(ResumeAnalysis.user_id == user_id)
        .order_by(ResumeAnalysis.created_at.desc())
        .limit(1)
    )
    row = result.scalar_one_or_none()
    return row.analysis_json if row else None

# --- Active goals -----------------------------------------------------------
async def _get_active_goals(db: AsyncSession, user_id) -> list[dict]:
    result = await db.execute(
        select(Goal)
        .where(Goal.user_id == user_id)
        .where(Goal.status_pct < 100.0)
        .order_by(Goal.deadline.asc().nullslast())
    )
    return [
        {
            "title": g.title,
            "deadline": g.deadline.isoformat() if g.deadline else None,
            "priority": g.priority,
            "status_pct": g.status_pct,
        }
        for g in result.scalars().all()
    ]

# --- Recent job matches ------------------------------------------------------
async def _get_recent_job_matches(db: AsyncSession, user_id, limit: int = MAX_RECENT_JOB_MATCHES) -> list[dict]:
    result = await db.execute(
        select(JobDescription)
        .where(JobDescription.user_id == user_id)
        .where(JobDescription.analysis_result.isnot(None))
        .order_by(JobDescription.created_at.desc())
        .limit(limit)
    )
    out = []
    for jd in result.scalars().all():
        overall = (jd.analysis_result or {}).get("overall_match", {})
        out.append({
            "role": jd.role,
            "company": jd.company,
            "match_percentage": overall.get("percentage"),
            "match_label": overall.get("label"),
        })
    return out

# --- Claim risk details ------------------------------------------------------
async def _get_claim_risk_details(db: AsyncSession, user_id) -> list[dict]:
    """Each entry carries "unsupported_claims" (the real skill/tech
    strings the Claim Audit found with no supporting GitHub evidence),
    which confidence_reconciliation.py relies on to discount the right
    skill's top_skills confidence, not just flag the project.
    """
    proj_result = await db.execute(select(Project.id, Project.name).where(Project.user_id == user_id))
    projects_by_id = {pid: name for pid, name in proj_result.all()}
    if not projects_by_id:
        return []
    audit_result = await db.execute(
        select(ProjectClaimAuditReview).where(ProjectClaimAuditReview.project_id.in_(projects_by_id.keys()))
    )
    details: list[dict] = []
    for row in audit_result.scalars().all():
        report_json = row.report_json or {}
        narrative = report_json.get("narrative", {})
        facts = report_json.get("facts", {})
        level = narrative.get("risk_level", "low")
        if level in ("high", "medium"):
            details.append({
                "project": projects_by_id.get(row.project_id, "Unknown project"),
                "risk_level": level,
                "headline": narrative.get("headline", ""),
                "unsupported_claims": facts.get("unsupported_claims", []),
            })
    return details

# --- Technology breadth helper ------------------------------------------------
def _build_technology_breadth(github_knowledge: dict) -> dict:
    all_technologies = github_knowledge.get("all_technologies", [])
    technology_depth = github_knowledge.get("technology_depth", {})
    deep_or_better_count = sum(
        1 for d in technology_depth.values() if isinstance(d, dict) and d.get("score", 0) >= DEEP_OR_BETTER_DEPTH_FLOOR
    )
    return {
        "total_distinct_technologies": len(all_technologies),
        "technologies_with_depth_data": len(technology_depth),
        "deep_or_better_count": deep_or_better_count,
    }

# --- Evidence hash (new version) --------------------------------------------
def _compute_evidence_hash(evidence: list[dict]) -> str:
    """Stable hash of the all_sources skill evidence used for role_fit.
    Two refreshes with the exact same (skill, confidence) pairs hash
    identically — see _get_cached_role_fit for how this skips a
    redundant LLM call.
    """
    normalized = sorted((e["skill"], round(e.get("confidence", 0.0), 3)) for e in evidence)
    raw = json.dumps(normalized, sort_keys=True)
    return hashlib.sha256(raw.encode()).hexdigest()

