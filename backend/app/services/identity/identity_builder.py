# --- Top skills implementation -------------------------------------------------
async def _get_top_skills(db: AsyncSession, user_id, limit: int = MAX_TOP_SKILLS) -> list[dict]:
    """Top-N reconciled skills, sorted by (already-reconciled) confidence
    descending. Delegates entirely to the shared, unbounded
    reconciled_confidence.get_reconciled_skill_confidences() — see that
    module's docstring for why reconciliation is computed once, there,
    instead of being duplicated per top-N-slice caller.

    Note: because reconciliation is now applied BEFORE this slice
    (rather than after, on an already-chosen top-N), a skill whose
    confidence gets discounted below another skill's may no longer make
    the cut. That's intentional — it's the fix for top_skills previously
    being able to show a stale/incorrect confidence number for a
    flagged skill that should have dropped out of the top N entirely.
    """
    reconciled = await get_reconciled_skill_confidences(db, user_id)
    if not reconciled:
        return []
    ranked = sorted(reconciled.values(), key=lambda e: e["confidence"], reverse=True)
    return ranked[:limit]

