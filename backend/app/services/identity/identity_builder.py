# --- Cached role_fit ----------------------------------------------------------
async def _get_cached_role_fit(db: AsyncSession, user_id, evidence_hash: str) -> list[dict] | None:
    """Returns the previous snapshot's role_fit if its stored evidence
    hash matches the CURRENT all_sources evidence exactly. Only reads
    the most recent VALID (non-invalidated) snapshot — reusing a rating
    that's since been flagged as known-bad would defeat the point of
    invalidation (audit finding #3).
    """
    result = await db.execute(
        select(EngineeringIdentity)
        .where(EngineeringIdentity.user_id == user_id)
        .where(EngineeringIdentity.is_invalidated.is_(False))
        .order_by(EngineeringIdentity.created_at.desc())
        .limit(1)
    )
    row = result.scalar_one_or_none()
    if row is None or not isinstance(row.facts_json, dict):
        return None
    if row.facts_json.get("role_fit_evidence_hash") != evidence_hash:
        return None
    cached = row.facts_json.get("role_fit")
    return cached if isinstance(cached, list) and cached else None

