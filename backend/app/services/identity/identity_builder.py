"""Builds the deterministic IdentityFacts object — the ONLY input the
Engineering Identity synthesis LLM call (identity_synthesizer.py) is
allowed to reason over (with the one deliberate exception of role_fit,
which is itself LLM-generated by services/identity/role_fit.py). Pulls
from every module that already computes real, verified facts.

Reconciliation fix (Critical, Engineering Identity audit): top_skills'
confidence numbers are reconciled against claim_risk_details and
timeline_plausibility_notes BEFORE being placed on the returned
IdentityFacts — see confidence_reconciliation.py.

Role-fit caching fix: the all_sources role_fit LLM call is skipped and
reused from the previous EngineeringIdentity snapshot whenever the
underlying scoped skill evidence hasn't actually changed — see
_compute_evidence_hash / _get_cached_role_fit below.

Recency + completeness fix (audit findings #1/#2): source_freshness and
evidence_coverage are now computed alongside everything else — see
freshness.py. Neither is derived from any of the OTHER facts here; both
read timestamps directly, independent of whether a given source
happened to have anything interesting to say this time.
"""
